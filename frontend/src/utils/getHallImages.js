export const getDynamicVenueImages = (hall) => {
  if (!hall) return [];
  if (hall.photos && hall.photos.length >= 8) {
    return hall.photos;
  }
  
  const key = hall._id || hall.name || '';
  let hash = 0;
  for (let i = 0; i < key.length; i++) {
    hash = key.charCodeAt(i) + ((hash << 5) - hash);
  }
  const poolIndex = Math.abs(hash) % VENUE_IMAGE_POOLS.length;
  const pool = VENUE_IMAGE_POOLS[poolIndex];
  
  const basePhotos = hall.photos && hall.photos.length > 0 ? hall.photos : [];
  const merged = [...basePhotos];
  
  for (const img of pool) {
    if (!merged.includes(img)) {
      merged.push(img);
    }
  }
  return merged;
};

export const getPrimaryHallPhoto = (hall) => {
  if (!hall) return 'https://images.unsplash.com/photo-1519167758481-83f550bb49b3?auto=format&fit=crop&q=80&w=1200';
  const images = getDynamicVenueImages(hall);
  return images[0] || 'https://images.unsplash.com/photo-1519167758481-83f550bb49b3?auto=format&fit=crop&q=80&w=1200';
};
